    public void setDatos(){
        
        DefaultComboBoxModel box1 = new DefaultComboBoxModel();
        DefaultComboBoxModel box2 = new DefaultComboBoxModel();
        DefaultComboBoxModel box3 = new DefaultComboBoxModel();
        
        box1.addElement("Seleccione una especie");
        
        for(Especie esp : Controlador.getEspecies()){
            
            box1.addElement(esp.getNombre());
            
        }
        
        jComboBox1.setModel(box1);
        
        box2.addElement("Seleccione un sector");
        
        for(Sector sec : Controlador.getSectores()){
            
            box2.addElement(sec.getNumero());
            
        }
        
        jComboBox2.setModel(box2);
        
        box3.addElement("Seleccione un Pais");
        
        for(Pais pa : Controlador.getPaises()){
            
            box3.addElement(pa.getNombre());
            
        }
        
        jComboBox3.setModel(box3);
        
        this.edad.setInputVerifier(new IntegerInputVerifier());
        this.peso.setInputVerifier(new DoubleInputVerifier());
        
        jComboBox1.addActionListener(evt -> actualizarSectoresDisponibles());
        jComboBox1.addActionListener(e -> actualizarEstadoTextField());
    
    // Actualizar sectores inicialmente
        actualizarSectoresDisponibles();
        
    }
      
    private void actualizarSectoresDisponibles() {
        // Obtener especie seleccionada
        String nombreEspecie = (String) jComboBox1.getSelectedItem();
        Especie especieSeleccionada = null;
                
        // Buscar la especie por nombre
        for (Especie esp : Controlador.getEspecies()) {
            if (esp.getNombre().equals(nombreEspecie)) {
                especieSeleccionada = esp;
                break;
            }
        }

        if (especieSeleccionada != null) {
            // Filtrar sectores por tipo de alimentación
            DefaultComboBoxModel<String> modeloSectores = new DefaultComboBoxModel<>();
            TipoAlimentacion alimentacionRequerida = especieSeleccionada.getTipoAlimentacion();
            modeloSectores.addElement("Seleccione un Sector");
            for (Sector sec : Controlador.getSectores()) {
                if (sec.getTipoAlimentacion().equals(alimentacionRequerida)) {
                    String item = String.valueOf(sec.getNumero());
                    modeloSectores.addElement(item);
                }
            }

            jComboBox2.setModel(modeloSectores);
            
        }
    }
    
    private void actualizarEstadoTextField() {
        String nombreEspecieSeleccionada = (String) jComboBox1.getSelectedItem();
        Especie especie = null;
        
        for (Especie esp : Controlador.getEspecies()) {
            if (esp.getNombre().equals(nombreEspecieSeleccionada)) {
                especie = esp;
                break;
            }
        }

        if (especie != null) {
            
            this.comidaFija.setEnabled(especie.getTipoAlimentacion().esHerbivoro());
            
        }
        
    }
