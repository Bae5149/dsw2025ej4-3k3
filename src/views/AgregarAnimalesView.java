    private void agregarAnimalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarAnimalActionPerformed
        // TODO add your handling code here:

        String nombreEspecie = (String) jComboBox1.getSelectedItem();
        int numeroSector = Integer.parseInt((String) jComboBox2.getSelectedItem());
        Especie especieS = null;
        Sector sector = null;
        Pais pais = null;

        // Buscar la especie por nombre
        for (Especie esp : Controlador.getEspecies()) {
            if (esp.getNombre().equals(nombreEspecie)) {
                especieS = esp;
                break;
            }
        }

        for (Sector sec : Controlador.getSectores()){
            if (sec.getNumero() == numeroSector) {
                sector = sec;
                break;
            }
        }

        for (Pais pa : Controlador.getPaises()){
            if (pa.getNombre().equals((String)this.jComboBox3.getSelectedItem())) {
                pais = pa;
                break;
            }
        }

        if(especieS.getTipoAlimentacion().esCarnivoro()){

            try {
                Controlador.agregarAnimal(null, new Carnivoro(Integer.parseInt(this.edad.getText()),Double.parseDouble(this.peso.getText()),especieS,sector,pais));
            } catch (InvalidPropertiesFormatException ex) {
                Logger.getLogger(AgregarAnimalesView.class.getName()).log(Level.SEVERE, null, ex);
            }

        }else{

            try {
                Controlador.agregarAnimal(new Herbivoro(Integer.parseInt(this.edad.getText()),Double.parseDouble(this.peso.getText()),especieS,sector,Double.parseDouble(this.comidaFija.getText()),pais),null);
            } catch (InvalidPropertiesFormatException ex) {
                Logger.getLogger(AgregarAnimalesView.class.getName()).log(Level.SEVERE, null, ex);
            }

        }

    }//GEN-LAST:event_agregarAnimalActionPerformed

